#!/usr/bin/env python3
# Produces vendor/google/gapps-kk (prebuilt modules + gapps-kk.mk) from an unpacked Open GApps 4.4
# package (folders <package>/<dpi>/{app,priv-app}, <package>/common/{lib,etc,...}).
# usage: make-gapps-kk.py <unpacked packages> <vendor/google/gapps-kk>
import os, shutil, sys
src, out = sys.argv[1], sys.argv[2]
DPI = "nodpi"  # 560 dpi: the density-independent version (all resources)
# APKs that replace an AOSP app
OVERRIDES = {"SetupWizard": "Provision", "Velvet": "QuickSearchBox",
             "GoogleOneTimeInitializer": "OneTimeInitializer"}

if os.path.exists(out):
    shutil.rmtree(out)
os.makedirs(out)
mods, copies = [], []
for pkg in sorted(os.listdir(src)):
    base = os.path.join(src, pkg)
    for kind in ("app", "priv-app"):
        d = os.path.join(base, DPI, kind)
        if not os.path.isdir(d):
            continue
        for apk in sorted(os.listdir(d)):
            name = apk[:-4]
            os.makedirs(os.path.join(out, kind), exist_ok=True)
            shutil.copy2(os.path.join(d, apk), os.path.join(out, kind, apk))
            mods.append((name, kind))
    common = os.path.join(base, "common")
    if os.path.isdir(common):
        for root, _, files in os.walk(common):
            for f in files:
                rel = os.path.relpath(os.path.join(root, f), common)
                dst = os.path.join(out, "system", rel)
                os.makedirs(os.path.dirname(dst), exist_ok=True)
                shutil.copy2(os.path.join(root, f), dst)
                copies.append(rel)

with open(os.path.join(out, "Android.mk"), "w") as mk:
    mk.write("# Google services (Open GApps 4.4 nano), APKs signed by Google: PRESIGNED. No\n"
             "# LOCAL_DEX_PREOPT (KitKat preopts as soon as it is defined, even to false): APKs untouched.\n"
             "# Generated by make-gapps-kk.py.\n"
             "LOCAL_PATH := $(call my-dir)\n")
    for name, kind in mods:
        mk.write("\ninclude $(CLEAR_VARS)\nLOCAL_MODULE := %s\nLOCAL_MODULE_CLASS := APPS\n"
                 "LOCAL_MODULE_SUFFIX := .apk\nLOCAL_MODULE_TAGS := optional\nLOCAL_SRC_FILES := %s/%s.apk\n"
                 "LOCAL_CERTIFICATE := PRESIGNED\n" % (name, kind, name))
        if kind == "priv-app":
            mk.write("LOCAL_PRIVILEGED_MODULE := true\n")
        if name in OVERRIDES:
            mk.write("LOCAL_OVERRIDES_PACKAGES := %s\n" % OVERRIDES[name])
        mk.write("include $(BUILD_PREBUILT)\n")

with open(os.path.join(out, "gapps-kk.mk"), "w") as mk:
    mk.write("# Google services for KitKat (Open GApps 4.4 nano): services, Play Store, setup wizard,\n"
             "# search and speech recognition. Generated by make-gapps-kk.py.\n"
             "PRODUCT_PACKAGES += \\\n" + " \\\n".join("    " + n for n, _ in mods) + "\n\n")
    mk.write("PRODUCT_COPY_FILES += \\\n" + " \\\n".join(
        "    vendor/google/gapps-kk/system/%s:system/%s" % (c, c) for c in sorted(copies)) + "\n\n")
    mk.write("PRODUCT_PROPERTY_OVERRIDES += \\\n    ro.setupwizard.mode=OPTIONAL \\\n"
             "    ro.com.google.clientidbase=android-google\n")
print(len(mods), "APKs,", len(copies), "files")
