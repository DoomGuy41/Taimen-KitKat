#!/usr/bin/env python3
# Generates the GLES shims: one exported symbol per GL function known to KitKat (entries.in) and
# present in the Android 11 Adreno library, jumping to it through a table filled at load time
# (libhyb). usage: gen_stubs.py <entries.in> <Android 11 lib> <output prefix> <table name>
import re, subprocess, sys
entries, lib, out, table = sys.argv[1:5]
names = re.findall(r'GL_ENTRY\([^,]+,\s*(\w+)', open(entries).read())
exp = set()
for l in subprocess.run(["readelf", "-W", "--dyn-syms", lib], capture_output=True, text=True).stdout.splitlines():
    f = l.split()
    if len(f) >= 8 and f[3] == "FUNC" and f[6] != "UND" and f[4] in ("GLOBAL", "WEAK"):
        exp.add(f[7].split("@")[0])
names = [n for n in names if n in exp]
with open(out + ".S", "w") as s:
    s.write("@ generated by gen_stubs.py from %s: %d functions\n" % (lib.split("/")[-1], len(names)))
    s.write("    .syntax unified\n    .arm\n    .text\n    .hidden %s\n" % table)
    for i, n in enumerate(names):
        s.write("    .globl %s\n    .type %s, %%function\n    .align 2\n%s:\n" % (n, n, n))
        s.write("    ldr r12, .L%d\n.Lp%d:\n    ldr pc, [pc, r12]\n.L%d:\n    .word %s + %d - (.Lp%d + 8)\n" % (i, i, i, table, 4 * i, i))
    s.write("    .section .note.GNU-stack,\"\",%progbits\n")
with open(out + "_names.c", "w") as c:
    c.write("/* generated by gen_stubs.py: %d functions */\n" % len(names))
    c.write("const char *const %s_names[] = {\n" % table)
    for n in names:
        c.write('    "%s",\n' % n)
    c.write("    0\n};\n")
    c.write("void *%s[%d] __attribute__((visibility(\"hidden\")));\n" % (table, len(names)))
print("%s: %d functions" % (out, len(names)))
